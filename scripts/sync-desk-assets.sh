#!/usr/bin/bash
# sync-desk-assets.sh — vendor the Desk dock asset from the sibling canfar-lab
# checkout into scripts/lib/astroai-dock.html, and keep config/desk-assets.lock
# in sync so `make desk-assets-check` can detect drift without the sibling.
#
# The dock is single-sourced in canfar-lab (src/canfar_lab/data/desk/dock.html):
# the laptop cockpit injects it behind its loopback proxy, and the Studio image
# injects the same bytes behind /api/studio/sync. Both proxies stay stdlib-only;
# only this HTML asset is shared.
#
# Usage:
#   make sync-desk-assets          # refresh scripts/lib/astroai-dock.html + lock
#   make desk-assets-check         # fail on drift (Docker-free CI gate)
set -euo pipefail
cd "$(dirname "$0")/.."

LAB_DIR="${CANFAR_LAB_DIR:-$(test -d ../canfar-lab && echo ../canfar-lab || echo ../astroai-lab)}"
SRC="${LAB_DIR}/src/canfar_lab/data/desk/dock.html"
DST="scripts/lib/astroai-dock.html"
LOCK="config/desk-assets.lock"

sha_of() { sha256sum "$1" | awk '{print $1}'; }

rev_of() {
    # <meta name="astroai-dock-revision" content="N"> — the asset self-identifies.
    sed -n 's/.*astroai-dock-revision" content="\([0-9][0-9]*\)".*/\1/p' "$1" | head -1
}

lock_value() {
    local key="$1"
    [[ -f "${LOCK}" ]] || return 0
    sed -n "s/^${key}=//p" "${LOCK}" | head -1
}

fail() {
    echo "desk-assets: $*" >&2
    exit 1
}

if [[ "${1:-}" == "--check" ]]; then
    [[ -f "${DST}" ]] || fail "missing ${DST} — run: make sync-desk-assets"
    [[ -f "${LOCK}" ]] || fail "missing ${LOCK} — run: make sync-desk-assets"
    want_sha="$(lock_value dock_sha256)"
    want_rev="$(lock_value dock_revision)"
    got_sha="$(sha_of "${DST}")"
    got_rev="$(rev_of "${DST}")"
    [[ -n "${want_sha}" ]] || fail "lock has no dock_sha256 — run: make sync-desk-assets"
    [[ -n "${got_rev}" ]] || fail "${DST} has no astroai-dock-revision — re-vendor it"
    if [[ "${want_sha}" != "${got_sha}" || "${want_rev}" != "${got_rev}" ]]; then
        fail "${DST} drifted from ${LOCK} (lock rev ${want_rev:-?} sha ${want_sha:0:12}… vs file rev ${got_rev} sha ${got_sha:0:12}…) — run: make sync-desk-assets"
    fi
    echo "desk-assets: vendor matches lock (rev ${got_rev}, sha256 ${got_sha:0:12}…)"
    exit 0
fi

[[ -f "${SRC}" ]] || fail "missing ${SRC} — clone canfar-lab as a sibling or set CANFAR_LAB_DIR"
rev="$(rev_of "${SRC}")"
[[ -n "${rev}" ]] || fail "${SRC} has no astroai-dock-revision meta"
cp "${SRC}" "${DST}"
sha="$(sha_of "${DST}")"
{
    echo "# Generated by scripts/sync-desk-assets.sh — do not edit."
    echo "# Vendors canfar-lab src/canfar_lab/data/desk/dock.html as"
    echo "# scripts/lib/astroai-dock.html; \`make desk-assets-check\` verifies the bytes."
    echo "dock_sha256=${sha}"
    echo "dock_revision=${rev}"
} >"${LOCK}"
echo "desk-assets: vendored ${SRC} → ${DST} (rev ${rev}, sha256 ${sha:0:12}…)"
